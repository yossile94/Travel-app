// Sprint 10 D15: the panel's validators and the database CHECKs run against
// one table. This writes supabase/tests/database/admin_cases.test.sql from
// supabase/tests/fixtures/admin_cases.json: each case is written as the
// service role would, and must pass or fail the CHECKs as the panel says.
// (A date in the future is the panel's rule only: no CHECK can say "today".)
//   node scripts/gen-admin-cases.mjs          writes the file
//   node scripts/gen-admin-cases.mjs --check  fails when it is stale (CI)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const fixture = path.join(root, 'supabase/tests/fixtures/admin_cases.json');
const target = path.join(root, 'supabase/tests/database/admin_cases.test.sql');

const q = (v) => (v === null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const expand = (note) => (/^x\d+$/.test(note) ? `repeat('x', ${note.slice(1)})` : q(note.trim()));
const num = (v) => (String(v).trim() === '' ? 'null' : String(Number(v)));

export function render({ entry, mct }) {
  const lines = [
    '-- GENERATED by scripts/gen-admin-cases.mjs from',
    '-- supabase/tests/fixtures/admin_cases.json. Do not edit by hand.',
    '-- Sprint 10 D15: the CHECKs accept and refuse what the panel does.',
    'begin;',
    'create extension if not exists pgtap with schema extensions;',
    `select plan(${entry.length + mct.length});`,
  ];
  entry.forEach((c, i) => {
    const adm0 = `Z${String(i).padStart(2, '0')}`.slice(0, 3).replace(/^Z(\d)$/, 'Z0$1');
    const sql =
      `insert into public.country_advisories (adm0, entry_status, entry_note, entry_source_url, entry_verified_at, passport_validity_months) ` +
      `values ('${adm0}', ${q(c.input.status)}, ${expand(c.input.note)}, ${q(c.input.source.trim())}, ${q(c.input.verified)}, ${num(c.input.months)})`;
    lines.push(
      c.ok
        ? `select lives_ok($$${sql}$$, ${q(`entry: ${c.name}`)});`
        : `select throws_ok($$${sql}$$, '23514', null, ${q(`entry: ${c.name}`)});`,
    );
  });
  mct.forEach((c, i) => {
    // One code per case, so an accepted row never collides with the next.
    const iata = `Q${String.fromCharCode(65 + Math.floor(i / 26))}${String.fromCharCode(65 + (i % 26))}`;
    const code = /^[A-Z]{3}$/.test(c.input.iata) ? iata : c.input.iata;
    const sql =
      `insert into public.min_connection_times (iata, minutes, source_url, verified_at) ` +
      `values (${q(code)}, ${num(c.input.minutes)}, ${q(c.input.source)}, ${q(c.input.verified)})`;
    lines.push(
      c.ok
        ? `select lives_ok($$${sql}$$, ${q(`mct: ${c.name}`)});`
        : `select throws_ok($$${sql}$$, '23514', null, ${q(`mct: ${c.name}`)});`,
    );
  });
  lines.push('', 'select * from finish();', 'rollback;', '');
  return lines.join('\n');
}

const sql = render(JSON.parse(fs.readFileSync(fixture, 'utf8')));
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== sql) {
    console.error('admin_cases.test.sql is stale: run node scripts/gen-admin-cases.mjs');
    process.exit(1);
  }
} else {
  fs.writeFileSync(target, sql);
}
