// Sprint 7 AC-1 (Raz 2): the connection rule runs in the app and in the
// database, so both are tested against one table. This writes the pgTAP part
// of supabase/tests/database/connection_cases.test.sql from
// supabase/tests/fixtures/connection_cases.json.
//   node scripts/gen-connection-cases.mjs          writes the file
//   node scripts/gen-connection-cases.mjs --check  fails when it is stale (CI)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const fixture = path.join(root, 'supabase/tests/fixtures/connection_cases.json');
const target = path.join(root, 'supabase/tests/database/connection_cases.test.sql');

const q = (v) => (v === null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const USER = '00000000-0000-4000-8000-0000000007aa';

export function render({ cases }) {
  const lines = [
    '-- GENERATED by scripts/gen-connection-cases.mjs from',
    '-- supabase/tests/fixtures/connection_cases.json. Do not edit by hand.',
    '-- Sprint 7 AC-1: trip_connections() gives the pairs the app gives.',
    'begin;',
    'create extension if not exists pgtap with schema extensions;',
    `select plan(${cases.length});`,
    `insert into auth.users (id, email) values ('${USER}', 'conn@example.test');`,
  ];
  cases.forEach((c, i) => {
    const trip = `10000000-0000-4000-8000-${String(i + 1).padStart(12, '0')}`;
    lines.push(
      '',
      `-- ${c.name}`,
      `insert into public.trips (id, user_id, country_adm0, title, start_date, end_date)`,
      `values ('${trip}', '${USER}', 'THA', 'T', '2026-11-30', '2026-12-20');`,
    );
    for (const f of c.flights) {
      // Ids are unique per case: the trip's number replaces the first group.
      const id = `${String(i + 1).padStart(8, '0')}${f.id.slice(8)}`;
      const date = (f.depSched ?? '2026-12-01').slice(0, 10);
      lines.push(
        `insert into public.flights (id, trip_id, user_id, direction, flight_number_input, flight_number,`,
        `  dep_date_local, dep_iata, dep_tz, arr_iata, arr_tz, dep_sched, arr_sched)`,
        `values ('${id}', '${trip}', '${USER}', ${q(f.direction)}, 'XX1', 'XX1', '${date}',`,
        `  ${q(f.dep)}, 'UTC', ${q(f.arr)}, ${f.arr === null ? 'null' : "'UTC'"}, ${q(f.depSched)}, ${q(f.arrSched)});`,
      );
    }
    const expected = c.expected.map(
      ([a, b]) =>
        `${String(i + 1).padStart(8, '0')}${a.slice(8)}>${String(i + 1).padStart(8, '0')}${b.slice(8)}`,
    );
    lines.push(
      `select is(`,
      `  (select coalesce(string_agg(prev_id || '>' || next_id, ',' order by prev_id), '')`,
      `   from public.trip_connections('${trip}')),`,
      `  ${q(expected.sort().join(','))},`,
      `  ${q(c.name)}`,
      `);`,
    );
  });
  lines.push('', 'select * from finish();', 'rollback;', '');
  return lines.join('\n');
}

const sql = render(JSON.parse(fs.readFileSync(fixture, 'utf8')));
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== sql) {
    console.error('connection_cases.test.sql is stale: run node scripts/gen-connection-cases.mjs');
    process.exit(1);
  }
} else {
  fs.writeFileSync(target, sql);
}
