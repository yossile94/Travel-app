// Sprint 10 design 19, 29: the panel's CSS variables come from the design
// tokens, the app's single source. color.light.text.primary becomes
// --color-text-primary (light only this sprint), plus radius, space and size.
//   node scripts/build-tokens.mjs          writes src/app/tokens.css
//   node scripts/build-tokens.mjs --check  fails when it is stale (tests)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.join(here, '../../../docs/design/tokens.json');
const target = path.join(here, '../src/app/tokens.css');

export function render(tokens) {
  const lines = [];
  for (const [key, value] of Object.entries(tokens)) {
    if (key.startsWith('$') || typeof value === 'object') continue;
    let name = null;
    if (key.startsWith('color.light.')) name = `color-${key.slice('color.light.'.length)}`;
    else if (/^(radius|space)\./.test(key)) name = key;
    if (!name) continue;
    const css = typeof value === 'number' ? `${value}px` : String(value);
    lines.push(`  --${name.replace(/[.]/g, '-')}: ${css};`);
  }
  return `/* GENERATED by scripts/build-tokens.mjs from docs/design/tokens.json. Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`;
}

const css = render(JSON.parse(fs.readFileSync(source, 'utf8')));
if (process.argv.includes('--check')) {
  if ((fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '') !== css) {
    console.error('tokens.css is stale: run npm run tokens -w apps/admin');
    process.exit(1);
  }
} else {
  fs.writeFileSync(target, css);
}
